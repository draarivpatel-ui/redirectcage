/*
 * Generate the CommonJS build from the single ESM source of truth.
 * The core has no imports and uses no ESM-only syntax beyond export
 * declarations, so the transform is intentionally small and auditable.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');

const EXPORT_NAMES = [
  'CODE', 'RedirectCageError', 'sanitizeRedirect', 'assertSafeRedirect',
  'isSafeRedirect', 'parseRedirectLocation', 'createRedirectGuard'
];

let body = source;
for (const name of EXPORT_NAMES) {
  const pattern = new RegExp('^export (?:const|class|function) ' + name + '\\b', 'm');
  if (!pattern.test(body)) throw new Error('CJS transform could not find export ' + name);
}
body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');

const defaultObjectStart = body.indexOf('const redirectcage = {');
if (defaultObjectStart === -1) throw new Error('CJS transform could not find the default export object');
if (!body.trimEnd().endsWith('export default redirectcage;')) {
  throw new Error('CJS transform could not find the default export statement');
}
body = body.slice(0, defaultObjectStart).trimEnd();

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body,
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = module.exports;',
  ''
].join('\n');

await mkdir(path.join(root, 'cjs'), { recursive: true });
await writeFile(path.join(root, 'cjs', 'index.cjs'), output, 'utf8');
process.stdout.write('cjs/index.cjs generated from src/index.mjs\n');
